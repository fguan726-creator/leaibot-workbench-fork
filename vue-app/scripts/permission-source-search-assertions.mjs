import assert from 'node:assert/strict'

// Shared by role editing and application/approval picker regression scenarios.
export async function verifySourceSearch(container) {
  const list = container.locator('.data-directory-list').first()
  const directory = list.locator('.data-directory').first()
  const source = directory.locator('.data-source').first()
  const sourceName = await source.locator('.data-source-toggle b').textContent()
  const names = await source.locator('.data-dataset-item > span').allTextContents()
  assert.ok(names.length, '二级节点应有可供检索的授权项')
  assert.equal(await list.locator('.source-search-trigger').count(), await list.locator('.data-source').count(), '每个二级节点有独立搜索入口')
  const checked = await list.locator('input[type=checkbox]:checked').count()
  const disabled = await list.locator('input[type=checkbox]:disabled').count()
  const allItems = await list.locator('.data-dataset-item').count()
  const otherSource = directory.locator('.data-source').nth(1)
  const otherCount = await otherSource.count() ? await otherSource.locator('.data-dataset-item').count() : null
  const toggle = source.locator('.data-source-toggle')
  const trigger = source.locator('.source-search-trigger')
  await toggle.click()
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false')
  await trigger.focus()
  await trigger.press('Enter')
  const input = source.locator('.source-search-box input')
  await input.waitFor()
  assert.equal(await input.evaluate((element) => document.activeElement === element), true, '展开二级搜索自动聚焦')
  await input.fill(` ${names[0].toLowerCase()} `)
  assert.deepEqual(await source.locator('.data-dataset-item > span').allTextContents(), names.filter((name) => name.toLowerCase().includes(names[0].toLowerCase())))
  if (otherCount !== null) assert.equal(await otherSource.locator('.data-dataset-item').count(), otherCount, '兄弟数据源不受影响')
  await input.press('Enter')
  assert.equal(await input.isVisible(), true, 'Enter 不提交外层表单或关闭弹窗')
  await input.fill('完全没有匹配项-qa')
  await source.getByText('暂无匹配的授权项', { exact: true }).waitFor()
  assert.equal(await source.locator('.data-dataset-item').count(), 0)
  assert.equal(await source.locator('.data-source-toggle b').textContent(), sourceName, '无结果仍保留二级标题')
  await source.locator('.source-search-clear').click()
  assert.equal(await source.locator('.data-dataset-item').count(), names.length)
  assert.equal(await input.evaluate((element) => document.activeElement === element), true, '清空后焦点留在输入框')
  await input.press('Escape')
  assert.equal(await source.locator('.source-search-box').count(), 0)
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false', '关闭搜索恢复搜索前折叠状态')
  assert.equal(await trigger.evaluate((element) => document.activeElement === element), true, 'Esc 返回搜索图标，不关闭外层弹窗')
  await toggle.click()

  // Parent source-name matches expose all its leaves, then child filtering narrows them.
  await directory.locator('.directory-search-trigger').click()
  const parentInput = directory.locator('.directory-search-box input')
  await parentInput.fill(sourceName)
  await trigger.click()
  await input.fill(names[0])
  assert.ok(await source.locator('.data-dataset-item').count() > 0)
  if (names.length > 1 && !names[1].includes(names[0])) {
    await parentInput.fill(names[1])
    await source.getByText('暂无匹配的授权项', { exact: true }).waitFor()
    await input.fill('')
    assert.deepEqual(await source.locator('.data-dataset-item > span').allTextContents(), names.filter((name) => name.toLowerCase().includes(names[1].toLowerCase())), '清空二级搜索不能越过一级筛选')
  }
  await parentInput.fill('')
  await input.fill(names[0])
  await directory.locator('.directory-search-trigger').click()
  assert.equal(await input.inputValue(), names[0], '关闭一级搜索不清除二级关键词')
  await trigger.click()
  assert.equal(await list.locator('.data-dataset-item').count(), allItems)
  assert.equal(await list.locator('input[type=checkbox]:checked').count(), checked, '搜索和清空均不改变授权勾选')
  assert.equal(await list.locator('input[type=checkbox]:disabled').count(), disabled, '搜索不改变只读与复制锁定状态')
}
