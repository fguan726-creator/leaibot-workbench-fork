function attachDiagnostics(page) {
  page.on('pageerror', (error) => browserErrors.push(`pageerror: ${error.message}`))
  page.on('console', (message) => {
    if (message.type() === 'error' && !message.text().startsWith('Failed to load resource')) browserErrors.push(`console: ${message.text()}`)
  })
  page.on('response', (response) => {
    if (response.status() >= 400) failedResponses.push(`${response.status()} ${response.url()}`)
  })
}

async function openModule(page, label) {
  await page.locator('.permission-module-rail button').filter({ hasText: label }).click()
  await page.getByRole('heading', { name: label, exact: true }).waitFor()
}

async function screenshot(page, name) {
  const file = path.join(os.tmpdir(), `leaibot-${name}.png`)
  await page.screenshot({ path: file, fullPage: true })
  screenshots.push(file)
}

async function openDatasetPicker(page, editor) {
  const component = editor.locator('[data-testid="custom-table-authorization-editor"]')
  await component.getByRole('button', { name: '编辑', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '编辑自定义授权数据集', exact: true })
  await dialog.waitFor()
  return { component, dialog }
}

async function tagOption(listbox, name) {
  const option = listbox.getByRole('option', { name, exact: true })
  return await option.count() ? option : listbox.getByText(name, { exact: true })
}

async function datasetRow(dialog, name) {
  return dialog.locator('.dataset-item').filter({ hasText: name })
}

async function selectDataset(dialog, name) {
  const row = await datasetRow(dialog, name)
  await row.getByRole('checkbox', { name: `选择${name}`, exact: true }).check()
  await dialog.locator('.config-panel').getByRole('heading', { name, exact: true }).waitFor()
  return row
}

async function assertPreview(scope, rowId, columnId, expected) {
  const cell = scope.locator(`td[data-row-id="${rowId}"][data-column-id="${columnId}"]`).last()
  await cell.waitFor()
  assert.equal(await cell.getAttribute('data-granted'), String(expected))
}

